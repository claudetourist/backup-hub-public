function subscribe<C extends EventChannel>(channel: C, callback: (payload: IpcEventMap[C]) => void): () => void {
  if (!EVENT_CHANNELS.includes(channel)) return () => undefined;
  const listener = (_event: unknown, payload: IpcEventMap[C]) => callback(payload);
  ipcRenderer.on(channel, listener);
  return () => {
    ipcRenderer.removeListener(channel, listener);
  };
}

